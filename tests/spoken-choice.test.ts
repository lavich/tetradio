import { describe, expect, it } from "vitest";
import { spokenChoice } from "../src/domain/course";

describe("произношение выбранного варианта", () => {
  it("предложение с пропуском звучит целиком с подставленным вариантом", () => {
    expect(spokenChoice("Εγώ ___ η Ελένη.", "είμαι")).toBe("Εγώ είμαι η Ελένη.");
  });
  it("русское пояснение в скобках не читается", () => {
    expect(spokenChoice("Κύριε Παύλο, ___ είστε από την Αθήνα; (κύριε — господин)", "εσείς")).toBe(
      "Κύριε Παύλο, εσείς είστε από την Αθήνα;",
    );
  });
  it("если в предложении остаётся русский — звучит только вариант", () => {
    expect(spokenChoice("Как сказать «я»: ___", "εγώ")).toBe("εγώ");
  });
  it("без пропуска звучит греческий вариант, русский — нет", () => {
    expect(spokenChoice("Η Άννα είναι από την Κύπρο.", "Σωστό")).toBe("Σωστό");
    expect(spokenChoice("Где живёт Анна?", "в Лимасоле")).toBeNull();
    expect(spokenChoice("Μένω ___ Λεμεσό.", "в")).toBeNull();
  });
});
