import { describe, expect, it } from "vitest";
import { conjugate, hasParadigm, irregularPast, verbGroup } from "../content/build/paradigm";

const table = (word: string, forms: string) => {
  const built = conjugate(word, forms);
  return built && [built.present.join(" "), built.past.join(" ")];
};

describe("спряжение правилами", () => {
  it.each([
    [
      "μένω",
      "аор. έμεινα; буд. θα μείνω",
      "μένω μένεις μένει μένουμε μένετε μένουν",
      "έμεινα έμεινες έμεινε μείναμε μείνατε έμειναν",
    ],
    [
      "μιλάω",
      "аор. μίλησα; буд. θα μιλήσω",
      "μιλάω μιλάς μιλάει μιλάμε μιλάτε μιλάνε",
      "μίλησα μίλησες μίλησε μιλήσαμε μιλήσατε μίλησαν",
    ],
    [
      "μπορώ",
      "аор. μπόρεσα; буд. θα μπορέσω",
      "μπορώ μπορείς μπορεί μπορούμε μπορείτε μπορούν",
      "μπόρεσα μπόρεσες μπόρεσε μπορέσαμε μπορέσατε μπόρεσαν",
    ],
    [
      "έρχομαι",
      "аор. ήρθα; буд. θα έρθω",
      "έρχομαι έρχεσαι έρχεται ερχόμαστε έρχεστε έρχονται",
      "ήρθα ήρθες ήρθε ήρθαμε ήρθατε ήρθαν",
    ],
    [
      "κοιμάμαι",
      "аор. κοιμήθηκα; буд. θα κοιμηθώ",
      "κοιμάμαι κοιμάσαι κοιμάται κοιμόμαστε κοιμάστε κοιμούνται",
      "κοιμήθηκα κοιμήθηκες κοιμήθηκε κοιμηθήκαμε κοιμηθήκατε κοιμήθηκαν",
    ],
    [
      "ασχολούμαι",
      "аор. ασχολήθηκα; буд. θα ασχοληθώ",
      "ασχολούμαι ασχολείσαι ασχολείται ασχολούμαστε ασχολείστε ασχολούνται",
      "ασχολήθηκα ασχολήθηκες ασχολήθηκε ασχοληθήκαμε ασχοληθήκατε ασχολήθηκαν",
    ],
    [
      "βαριέμαι",
      "аор. βαρέθηκα; буд. θα βαρεθώ",
      "βαριέμαι βαριέσαι βαριέται βαριόμαστε βαριέστε βαριούνται",
      "βαρέθηκα βαρέθηκες βαρέθηκε βαρεθήκαμε βαρεθήκατε βαρέθηκαν",
    ],
    [
      "ξέρω",
      "прош. ήξερα; буд. θα ξέρω",
      "ξέρω ξέρεις ξέρει ξέρουμε ξέρετε ξέρουν",
      "ήξερα ήξερες ήξερε ξέραμε ξέρατε ήξεραν",
    ],
    [
      "απολύω",
      "аор. απέλυσα; буд. θα απολύσω",
      "απολύω απολύεις απολύει απολύουμε απολύετε απολύουν",
      "απέλυσα απέλυσες απέλυσε απολύσαμε απολύσατε απέλυσαν",
    ],
    [
      "παραγγέλνω",
      "аор. παρήγγειλα; буд. θα παραγγείλω",
      "παραγγέλνω παραγγέλνεις παραγγέλνει παραγγέλνουμε παραγγέλνετε παραγγέλνουν",
      "παρήγγειλα παρήγγειλες παρήγγειλε παραγγείλαμε παραγγείλατε παρήγγειλαν",
    ],
    [
      "ταξιδεύω",
      "аор. ταξίδεψα; буд. θα ταξιδέψω",
      "ταξιδεύω ταξιδεύεις ταξιδεύει ταξιδεύουμε ταξιδεύετε ταξιδεύουν",
      "ταξίδεψα ταξίδεψες ταξίδεψε ταξιδέψαμε ταξιδέψατε ταξίδεψαν",
    ],
    [
      "βρίσκω",
      "аор. βρήκα; буд. θα βρω",
      "βρίσκω βρίσκεις βρίσκει βρίσκουμε βρίσκετε βρίσκουν",
      "βρήκα βρήκες βρήκε βρήκαμε βρήκατε βρήκαν",
    ],
    [
      "γίνομαι",
      "аор. έγινα; буд. θα γίνω",
      "γίνομαι γίνεσαι γίνεται γινόμαστε γίνεστε γίνονται",
      "έγινα έγινες έγινε γίναμε γίνατε έγιναν",
    ],
    [
      "εξηγώ",
      "аор. εξήγησα; буд. θα εξηγήσω",
      "εξηγώ εξηγείς εξηγεί εξηγούμε εξηγείτε εξηγούν",
      "εξήγησα εξήγησες εξήγησε εξηγήσαμε εξηγήσατε εξήγησαν",
    ],
  ])("%s", (word, forms, present, past) => {
    expect(table(word, forms)).toEqual([present, past]);
  });

  it.each([
    ["λέω", "аор. είπα; буд. θα πω"],
    ["τρώω", "аор. έφαγα; буд. θα φάω"],
    ["είμαι", "прош. ήμουν; буд. θα είμαι"],
    ["πίνω", "аор. ήπια; буд. θα πιω"],
  ])("%s — только явной таблицей", (word, forms) => {
    expect(conjugate(word, forms)).toBeNull();
  });

  it("таблица только у глагола с лицами", () => {
    expect(hasParadigm("μένω", "аор. έμεινα; буд. θα μείνω")).toBe(true);
    expect(hasParadigm("βρέχει", "аор. έβρεξε; буд. θα βρέξει")).toBe(false);
    expect(hasParadigm("ο φίλος", "мн. οι φίλοι")).toBe(false);
  });
});

describe("правила отказываются, где не уверены", () => {
  it.each([
    ["φέρνω", "аор. έφερα"],
    ["κοροϊδεύω", "аор. κορόιδεψα; буд. θα κοροϊδέψω"],
    ["πάω", "аор. πήγα; буд. θα πάω"],
    ["μιλάω/μιλώ", "аор. μίλησα; буд. θα μιλήσω"],
  ])("%s", (word, forms) => {
    expect(conjugate(word, forms)).toBeNull();
  });
});

describe("группа глагола по таблице настоящего", () => {
  it.each([
    ["A", ["μένω", "μένεις", "μένει", "μένουμε", "μένετε", "μένουν"]],
    ["A", ["αρέσω", "αρέσεις", "αρέσει", "αρέσουμε", "αρέσετε", "αρέσουν"]],
    ["B1", ["αγαπάω", "αγαπάς", "αγαπάει", "αγαπάμε", "αγαπάτε", "αγαπάνε"]],
    ["B1", ["προτιμώ", "προτιμάς", "προτιμά", "προτιμούμε", "προτιμάτε", "προτιμούν"]],
    ["B2", ["μπορώ", "μπορείς", "μπορεί", "μπορούμε", "μπορείτε", "μπορούν"]],
    ["B2", ["ζω", "ζεις", "ζει", "ζούμε", "ζείτε", "ζουν"]],
    ["mid", ["έρχομαι", "έρχεσαι", "έρχεται", "ερχόμαστε", "έρχεστε", "έρχονται"]],
    ["mid", ["κοιμάμαι", "κοιμάσαι", "κοιμάται", "κοιμόμαστε", "κοιμάστε", "κοιμούνται"]],
    ["mid", ["αρνούμαι", "αρνείσαι", "αρνείται", "αρνούμαστε", "αρνείστε", "αρνούνται"]],
    ["mid", ["βαριέμαι", "βαριέσαι", "βαριέται", "βαριόμαστε", "βαριέστε", "βαριούνται"]],
  ])("%s — %s", (group, present) => {
    expect(verbGroup(present)).toBe(group);
  });

  it.each([
    [["λέω", "λες", "λέει", "λέμε", "λέτε", "λένε"]],
    [["τρώω", "τρως", "τρώει", "τρώμε", "τρώτε", "τρώνε"]],
    [["ακούω", "ακούς", "ακούει", "ακούμε", "ακούτε", "ακούνε"]],
    [["είμαι", "είσαι", "είναι", "είμαστε", "είστε", "είναι"]],
  ])("%s — группу задаёт карточка", (present) => {
    expect(verbGroup(present)).toBeNull();
  });
});

describe("неправильное прошедшее по окончанию", () => {
  it.each([
    ["γράφω", "έγραψα"],
    ["αγαπάω", "αγάπησα"],
    ["περνάω", "πέρασα"],
    ["χάνω", "έχασα"],
    ["κλείνω", "έκλεισα"],
    ["αρρωσταίνω", "αρρώστησα"],
    ["περιμένω", "περίμενα"],
    ["σερβίρω", "σέρβιρα"],
    ["κοιμάμαι", "κοιμήθηκα"],
    ["σκέφτομαι", "σκέφτηκα"],
    ["χάνομαι", "χάθηκα"],
  ])("%s → %s — правильное", (headword, past) => {
    expect(irregularPast(headword, past)).toBe(false);
  });

  it.each([
    ["πηγαίνω", "πήγα"],
    ["βλέπω", "είδα"],
    ["μένω", "έμεινα"],
    ["παχαίνω", "πάχυνα"],
    ["φέρνω", "έφερα"],
    ["καταπίνω", "κατάπια"],
    ["έχω", "είχα"],
    ["θέλω", "ήθελα"],
    ["έρχομαι", "ήρθα"],
    ["γίνομαι", "έγινα"],
    ["είμαι", "ήμουν"],
    ["υπάρχω", "υπήρχα"],
  ])("%s → %s — неправильное", (headword, past) => {
    expect(irregularPast(headword, past)).toBe(true);
  });

  it.each([
    ["κάνω", "έκανα"],
    ["δίνω", "έδωσα"],
    ["βρίσκομαι", "βρέθηκα"],
    ["πλένομαι", "πλύθηκα"],
  ])("%s → %s — окончание правильное, смену основы правило не видит", (headword, past) => {
    expect(irregularPast(headword, past)).toBe(false);
  });
});
